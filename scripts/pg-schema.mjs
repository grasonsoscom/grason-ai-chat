// Writes prisma/postgres.prisma: the same schema with a PostgreSQL datasource.
// Local dev stays on SQLite (prisma/schema.prisma); Vercel builds use this copy.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider  = "postgresql"\n  directUrl = env("DATABASE_URL_UNPOOLED")');
if (out === src) throw new Error('prisma/schema.prisma: provider "sqlite" not found');
writeFileSync("prisma/postgres.prisma", "// Generated by scripts/pg-schema.mjs. Edit schema.prisma instead.\n" + out);
console.log("Wrote prisma/postgres.prisma");
